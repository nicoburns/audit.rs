/// Stylesheet generated by Tailwind CSS from `tailwind.css`.
const TAILWIND_CSS: Asset = asset!("/assets/tailwind.css");

/// Application routes.
///
/// This enum declares all valid routes in the app. Every variant is rendered by the component of
/// the same name (or the one given in the `#[route]` attribute), which receives the route
/// parameters as props.
///
/// The default route for `/:name` is to render a crate. Therefore, when adding new routes, one
/// must be careful to not alias an existing crate name. For example, adding a route with the path
/// `/serde` would mask the crate view for the `serde` crate.
#[derive(Clone, Routable, PartialEq, Debug)]
#[rustfmt::skip]
pub enum Route {
    /// Home view, shows search bar and summary.
    #[route("/")]
    Home {},

    /// About view, shows information about the application.
    #[route("/about")]
    About {},

    /// Search view, shows search results.
    #[route("/search/:query")]
    Search { query: String },

    /// Browse view, will load crate source and redirect to default file.
    #[route("/browse/:krate/:version")]
    Browse { krate: String, version: VersionId },

    /// File browse view.
    #[route("/browse/:krate/:version/:..path")]
    BrowseFile {
        krate: String,
        version: VersionId,
        path: FilePath,
    },

    /// Crate view, will make request to get most recent version and redirect.
    #[route("/:krate")]
    Crate { krate: String },

    /// Crates view, allows for diffing two crates.
    #[route("/:old_krate/:new_krate")]
    Crates {
        old_krate: String,
        new_krate: String,
    },

    /// File diff view between `old` and `new` versions.
    #[route("/:krate/:old_version/:new_version")]
    SingleSourceDiff {
        krate: String,
        old_version: VersionId,
        new_version: VersionId,
    },

    /// File diff view between `old` and `new` versions.
    #[route("/:krate/:old_version/:new_version/:..path")]
    SingleSourceFile {
        krate: String,
        old_version: VersionId,
        new_version: VersionId,
        path: FilePath,
    },

    /// File diff view, render differences in the file path between the crate versions.
    #[route("/:old_krate/:old_version/:new_krate/:new_version/:..path")]
    File {
        old_krate: String,
        old_version: VersionId,
        new_krate: String,
        new_version: VersionId,
        path: FilePath,
    },

    #[route("/repo/:krate/:version/files/:..path")]
    RepoFile {
        krate: String,
        version: VersionId,
        path: FilePath,
    },

    /// Route that is matched if no other route matches, shows error message.
    #[route("/:..segments", PageNotFound)]
    NotFound { segments: Vec<String> },
}

impl Route {
    /// Try to simplify a route.
    ///
    /// If the route is a multi-crate route, and the crates are identical, then simplify it to
    /// using a single-crate route.
    pub fn simplify(self) -> Self {
        match self {
            Route::File {
                old_krate,
                old_version,
                new_krate,
                new_version,
                path,
            } if old_krate == new_krate => Route::SingleSourceFile {
                krate: old_krate,
                old_version,
                new_version,
                path,
            },
            Route::Crates {
                old_krate,
                new_krate,
            } if old_krate == new_krate => Route::Crate { krate: old_krate },
            other => other,
        }
    }
}

/// File path inside of a crate, captured by the catch-all segment of a [`Route`].
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct FilePath(pub Utf8PathBuf);

impl FromIterator<String> for FilePath {
    fn from_iter<I: IntoIterator<Item = String>>(iter: I) -> Self {
        Self(iter.into_iter().collect())
    }
}

impl ToRouteSegments for FilePath {
    fn display_route_segments(&self, f: &mut Formatter<'_>) -> FmtResult {
        self.0.iter().collect::<Vec<_>>().display_route_segments(f)
    }
}

impl From<Utf8PathBuf> for FilePath {
    fn from(path: Utf8PathBuf) -> Self {
        Self(path)
    }
}

impl From<&str> for FilePath {
    fn from(path: &str) -> Self {
        Self(path.into())
    }
}

#[component]
fn Browse(krate: String, version: VersionId) -> Element {
    rsx! {
        Diff {
            src_name: krate.clone(),
            dst_name: krate,
            old: version.clone(),
            new: version,
        }
    }
}

#[component]
fn BrowseFile(krate: String, version: VersionId, path: FilePath) -> Element {
    rsx! {
        Diff {
            src_name: krate.clone(),
            dst_name: krate,
            old: version.clone(),
            new: version,
            path: path.0,
        }
    }
}

#[component]
fn Crate(krate: String) -> Element {
    rsx! {
        Diff {
            src_name: krate.clone(),
            dst_name: krate,
            old: VersionId::Named(VersionNamed::Previous),
            new: VersionId::Named(VersionNamed::Latest),
        }
    }
}

#[component]
fn Crates(old_krate: String, new_krate: String) -> Element {
    rsx! {
        Diff {
            src_name: old_krate,
            dst_name: new_krate,
            old: VersionId::Named(VersionNamed::Latest),
            new: VersionId::Named(VersionNamed::Latest),
        }
    }
}

#[component]
fn SingleSourceDiff(krate: String, old_version: VersionId, new_version: VersionId) -> Element {
    rsx! {
        Diff { src_name: krate.clone(), dst_name: krate, old: old_version, new: new_version }
    }
}

#[component]
fn SingleSourceFile(
    krate: String,
    old_version: VersionId,
    new_version: VersionId,
    path: FilePath,
) -> Element {
    rsx! {
        Diff {
            src_name: krate.clone(),
            dst_name: krate,
            old: old_version,
            new: new_version,
            path: path.0,
        }
    }
}

#[component]
fn File(
    old_krate: String,
    old_version: VersionId,
    new_krate: String,
    new_version: VersionId,
    path: FilePath,
) -> Element {
    rsx! {
        Diff {
            src_name: old_krate,
            dst_name: new_krate,
            old: old_version,
            new: new_version,
            path: path.0,
        }
    }
}

#[component]
fn RepoFile(krate: String, version: VersionId, path: FilePath) -> Element {
    rsx! {
        RepoFileView { krate, version, path: path.0 }
    }
}

#[component]
fn PageNotFound(segments: Vec<String>) -> Element {
    let _ = segments;
    rsx! {
        NotFound {}
    }
}

/// Render application.
#[component]
pub fn App() -> Element {
    rsx! {
        document::Stylesheet { href: TAILWIND_CSS }
        Router::<Route> {}
    }
}
